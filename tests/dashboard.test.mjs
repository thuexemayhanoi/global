import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import {publicationQueue,dashboardMarkdown,QUEUE_STATES,factoryStatus} from "../scripts/topic-factory-core.mjs";
import {loadTopicalMap} from "../scripts/seo/topical-authority-core.mjs";

const read=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const H=c=>c.repeat(64);
const row=(id,status="IDEA")=>({id,locale:id.slice(0,2).toLowerCase(),role:id[3]==="H"?"HUB":"SUPPORT",status});
const matrix={rows:["EN-H01","EN-S01","EN-S02","DE-H01","DE-S01","FR-H01","FR-S01","NL-H01","PT-H01","JA-H01","KO-H01"].map(id=>row(id)).concat([row("VI-H01","PUBLISHED")])};
const c=(id,status,extra={})=>({id,writer:"W1",session:"w1-dash",branch:"writer/w1-dash",status,source_sha256:H("a"),source_commit:"b".repeat(40),...extra});
const item=(id,decision,failed,extra={})=>({id,decision,failed,writer:"W1",session:"w1-dash",branch:"writer/w1-dash",source_sha256:H("a"),source_commit:"b".repeat(40),details:[],...extra});
const ledger={version:1,revision:42,claims:[
 c("EN-H01","SUBMITTED"),c("EN-S01","SUBMITTED"),c("EN-S02","SUBMITTED",{source_sha256:H("c")}),c("DE-H01","SUBMITTED"),
 c("DE-S01","SUBMITTED"),c("FR-H01","SUBMITTED",{revisions:[{},{},{}]}),c("FR-S01","SUBMITTED"),c("NL-H01","SUBMITTED"),
 c("VI-H01","SUBMITTED"),c("JA-H01","CLAIMED"),c("KO-H01","RELEASED")]};
const report={version:2,ledger_revision:41,items:[
 item("EN-H01","APPROVED_BY_POLICY",[]),item("EN-S01","REJECTED",["G4_EDITORIAL"]),item("EN-S02","REJECTED",["G4_EDITORIAL"]),
 item("DE-S01","REVIEW_REQUIRED",["G3_TOPIC_CLASS"]),item("FR-H01","REJECTED",["G1_DEPTH"]),item("FR-S01","WAIT_PARENT",["G2_PARENT_PUBLISHED"]),
 item("NL-H01","WAIT_STAGE",["G7_STAGE_CAP"])]};
const state={stage:"PILOT",paused:true,pause_reason:"Live QA inconclusive",published:[{id:"PT-H01",live_qa:"PENDING"},{id:"VI-H01",live_qa:"PASS"},{id:"X",live_qa:"FAIL"},{id:"Y",live_qa:"INCONCLUSIVE"}]};

test("every open SUBMITTED draft lands in exactly one queue state, from real report hashes only",()=>{
 const q=publicationQueue({matrix,ledger,report,state});
 assert.deepEqual(q.totals,{AWAITING_QA:2,APPROVED_BY_POLICY:1,REPAIR:1,HUMAN_REVIEW_REQUIRED:1,WAIT_PARENT:1,WAIT_STAGE:1,ESCALATED:1,BLOCKED:0});
 assert.equal(q.submitted_open,Object.values(q.totals).reduce((a,b)=>a+b,0));
 assert.equal(q.submitted_open,8,"the SUBMITTED draft whose page is PUBLISHED is not in the queue");
 assert.equal(q.submitted_live,1);
 assert.equal(q.claimed,1);
 assert.equal(q.byLocale.en.AWAITING_QA,1,"a report row for an older hash never speaks for the new revision");
 assert.deepEqual(q.live,{PUBLISH_STAGED:1,LIVE_QA_PASS:1,LIVE_QA_FAIL:1,LIVE_QA_INCONCLUSIVE:1});
 assert.equal(q.byWriter.W1.REPAIR,1);
 assert.equal(q.report_ledger_revision,41);
 const stale=publicationQueue({matrix,ledger,report:{version:1,items:report.items},state:null});
 assert.equal(stale.totals.AWAITING_QA,8,"an old-format report is never trusted");
});

test("the dashboard separates every pipeline state and never claims drafts as live or 10,000 as done",()=>{
 const status=factoryStatus({matrix:read("data/seo/master-matrix.json"),map:loadTopicalMap("."),ledger:read("factory/external-writers/claims.json"),
  registry:read("factory/external-writers/protected-drafts.json"),policy:read("data/seo/topic-factory/policy.json")});
 const q=publicationQueue({matrix,ledger,report,state});
 const md=dashboardMarkdown(status,{queue:q,ledger,slots:read("factory/external-writers/slots.json"),refill:{selected:[],research_needed:[]}});
 for(const label of ["READY","PROPOSED","CLAIMED","SUBMITTED","REPAIR","HUMAN_REVIEW_REQUIRED","WAIT_PARENT","WAIT_STAGE","ESCALATED","BLOCKED",
  "APPROVED_BY_POLICY","PUBLISH_STAGED","LIVE_QA_PASS","LIVE_QA_FAIL","LIVE_QA_INCONCLUSIVE","PUBLISHED","AWAITING QA"])assert.ok(md.includes(label),label);
 assert.match(md,/a SUBMITTED draft is not a live page/);
 assert.match(md,/planning ceiling, not progress/);
 assert.match(md,/\*\*PAUSED\*\*: Live QA inconclusive/);
 assert.match(md,/GitHub Actions never writes prose/);
 assert.doesNotMatch(md,/10,?000 (?:articles|topics) (?:published|done|complete)/i);
 assert.equal(QUEUE_STATES.length,8);
});

test("the committed dashboard is generator output with the queue sections, not a hand-made table",()=>{
 const md=fs.readFileSync("docs/CONTENT-FACTORY-DASHBOARD.md","utf8");
 assert.match(md,/^# Global Content Factory dashboard\n\nGenerated by `node scripts\/topic-factory\.mjs status --markdown`/);
 for(const h of ["## Topics and Writers","## Publication queue (SUBMITTED drafts not live yet)","## Auto Publisher","## Writer slots"])assert.ok(md.includes(h),h);
 const wf=fs.readFileSync(".github/workflows/auto-publisher.yml","utf8")+fs.readFileSync(".github/workflows/topic-factory.yml","utf8");
 assert.equal((wf.match(/topic-factory\.mjs status --markdown docs\/CONTENT-FACTORY-DASHBOARD\.md/g)||[]).length,3,"refreshed by the publisher (publish commit, after live QA) and the factory, all from data");
});

test("the publisher refreshes the dashboard after the live QA result, without touching the verdict or the drain",()=>{
 const y=fs.readFileSync(".github/workflows/auto-publisher.yml","utf8");
 const at=y.indexOf("- name: Refresh the dashboard from the recorded live QA result");
 const finalize=y.indexOf("- name: Record live QA, or revert the publish commit and pause"),drain=y.indexOf("- name: Dispatch next pair only after successful live QA");
 assert.ok(finalize>0&&at>finalize&&drain>at,"runs after the result is recorded and before the drain step");
 const step=y.slice(at,drain);
 assert.match(step,/if: \$\{\{ !cancelled\(\) && \(steps\.pub\.outputs\.ids != '' \|\| steps\.pub\.outputs\.recover != ''\) \}\}/,"also after a pause or a revert");
 assert.match(step,/continue-on-error: true/,"a dashboard problem never fails the publication run");
 assert.match(step,/git reset -q --hard origin\/main/,"regenerated from what is on main now");
 assert.match(step,/git add docs\/CONTENT-FACTORY-DASHBOARD\.md\n/,"commits only the dashboard");
 assert.doesNotMatch(step,/--force|push -f|\+HEAD|state\.json|git revert/);
 assert.doesNotMatch(step,/\n\s+id: /,"no step id, so nothing downstream can depend on it");
 assert.match(y.slice(drain),/if: \(steps\.pub\.outputs\.ids != '' \|\| steps\.pub\.outputs\.recover != ''\) && steps\.live\.outcome == 'success' && steps\.finalize\.outcome == 'success'\n/,"the drain condition is unchanged");
});
